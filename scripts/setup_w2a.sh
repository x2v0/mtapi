#!/usr/bin/env bash
# Search Android SDK / NDK / JDK in several common locations, not just ~/w2a.
cd "$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

# ── clone or update w2a ─────────────────────────────────────
W2A_DIR="${W2A_DIR:-$HOME/w2a}"
W2A_REPO="${W2A_REPO:-https://github.com/x2v0/w2a.git}"
if [ -d "$W2A_DIR/.git" ]; then
    echo "w2a: updating $W2A_DIR"
    git -C "$W2A_DIR" pull --ff-only || echo "w2a: pull failed (keeping local)"
elif [ -d "$W2A_DIR" ]; then
    echo "w2a: $W2A_DIR exists but not a git repo — skipping clone"
else
    echo "w2a: cloning $W2A_REPO → $W2A_DIR"
    git clone --depth 1 "$W2A_REPO" "$W2A_DIR"
fi
if [ -d "$W2A_DIR" ]; then
    echo "w2a: OK at $W2A_DIR"
else
    echo "WARNING: w2a not found — 'make apk' will fail"
fi
mkdir -p ~/tmp
export TMPDIR=~/tmp
set -euo pipefail

# ── SDK search paths ───────────────────────────────────────
SDK_CANDIDATES=(
    "${ANDROID_HOME:-}"
    "${ANDROID_SDK_ROOT:-}"
    "$HOME/android-sdk"
    "$HOME/Android/Sdk"
    "$HOME/Android/android-sdk"
    "$PREFIX/share/android-sdk"
    "$HOME/w2a/sdk"
    "$HOME/w2a/android-sdk"
)

# ── NDK search paths ───────────────────────────────────────
NDK_CANDIDATES=(
    "${ANDROID_NDK_HOME:-}"
    "${ANDROID_NDK_ROOT:-}"
    "$HOME/android-ndk"
    "$HOME/Android/ndk"
    "$HOME/android-sdk/ndk"
    "$HOME/Android/Sdk/ndk"
    "$PREFIX/share/android-ndk"
    "$HOME/w2a/ndk"
)

find_sdk() {
    local d
    for d in "${SDK_CANDIDATES[@]}"; do
        [ -z "$d" ] && continue
        if [ -d "$d" ] && { [ -d "$d/platform-tools" ] || [ -d "$d/platforms" ] || [ -d "$d/build-tools" ] || [ -d "$d/cmdline-tools" ]; }; then
            echo "$d"; return 0
        fi
    done
    return 1
}

find_ndk() {
    local d
    for d in "${NDK_CANDIDATES[@]}"; do
        [ -z "$d" ] && continue
        if [ -d "$d/toolchains/llvm/prebuilt" ] || [ -d "$d/ndk-build" ]; then
            echo "$d"; return 0
        fi
        # versioned subdir e.g. ndk/26.1.10909125
        if [ -d "$d" ]; then
            local v
            v="$(ls -1d "$d"/*/ 2>/dev/null | while read -r x; do
                    if [ -d "$x/toolchains" ] || [ -f "$x/ndk-build" ]; then echo "$x"; fi
                 done | tail -1 | sed 's:/*$::')"
            [ -n "$v" ] && { echo "$v"; return 0; }
        fi
    done
    return 1
}

find_jdk() {
    local d
    for d in \
        "${JAVA_HOME:-}" \
        "$HOME/jdk" \
        "$HOME/jdk-17" "$HOME/jdk-21" \
        "$PREFIX/lib/jvm/java-21-openjdk" \
        "$PREFIX/lib/jvm/java-17-openjdk" \
        "$HOME/w2a/jdk" ; do
        [ -z "$d" ] && continue
        if [ -x "$d/bin/javac" ] || [ -x "$d/bin/java" ]; then
            echo "$d"; return 0
        fi
    done
    # fallback: dir of javac in PATH
    local j
    j="$(command -v javac 2>/dev/null || command -v java 2>/dev/null || true)"
    [ -n "$j" ] && dirname "$(dirname "$j")" && return 0
    return 1
}

SDK="$(find_sdk || true)"
NDK="$(find_ndk || true)"
JDK="$(find_jdk || true)"

{
    echo '#!/usr/bin/env bash'
    echo '# Generated by scripts/setup_w2a.sh'
    echo 'export TMPDIR="${TMPDIR:-$HOME/tmp}"'
    echo 'mkdir -p "$TMPDIR"'
    [ -n "$SDK" ] && {
        echo "export ANDROID_HOME=\"$SDK\""
        echo "export ANDROID_SDK_ROOT=\"$SDK\""
        echo 'export PATH="$ANDROID_HOME/platform-tools:$ANDROID_HOME/cmdline-tools/latest/bin:$PATH"'
    }
    [ -n "$NDK" ] && {
        echo "export ANDROID_NDK_HOME=\"$NDK\""
        echo "export NDK=\"$NDK\""
        echo "export ANDROID_NDK_ROOT=\"$NDK\""
    }
    [ -n "$JDK" ] && {
        echo "export JAVA_HOME=\"$JDK\""
        echo 'export PATH="$JAVA_HOME/bin:$PATH"'
    }
    echo
    echo 'echo "env: SDK=$ANDROID_HOME NDK=$ANDROID_NDK_HOME JDK=$JAVA_HOME TMPDIR=$TMPDIR"'
} > scripts/env.sh
chmod 755 scripts/env.sh

if [ -n "$SDK" ]; then
    {
        echo "sdk.dir=$SDK"
        [ -n "$NDK" ] && echo "ndk.dir=$NDK"
    } > android/local.properties
    echo "wrote android/local.properties"
fi

echo "wrote scripts/env.sh"
echo "SDK=$SDK"
echo "NDK=$NDK"
echo "JDK=$JDK"

if [ -z "$SDK" ]; then
    echo
    echo "WARNING: no Android SDK found"
    echo "  install via:"
    echo "    1) Android Studio on host and copy sdk/"
    echo "    2) sdkmanager (Java part) — but aapt2/d8/x86_64 will not run on Termux"
    echo "    3) build APK on host / GitHub Actions instead"
fi
if [ -z "$NDK" ]; then
    echo "WARNING: no Android NDK found — gomobile bind will fail"
fi
if [ -z "$JDK" ]; then
    echo "WARNING: no JDK found — gradle will fail (try: pkg install openjdk-21)"
fi
