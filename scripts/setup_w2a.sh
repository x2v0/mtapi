#!/usr/bin/env bash
cd ~/dwn/mtapi
mkdir -p ~/tmp
export TMPDIR=~/tmp
set -euo pipefail

W2A="$HOME/w2a"
if [ ! -d "$W2A" ]; then
    echo "ERROR: $W2A not found"
    exit 1
fi

find_dir() {
    # $1 = base, $2 = marker path inside candidate dir
    local base="$1" marker="$2"
    [ -d "$base" ] || return 1
    [ -e "$base/$marker" ] && { echo "$base"; return 0; }
    while IFS= read -r d; do
        [ -e "$d/$marker" ] && { echo "$d"; return 0; }
    done < <(find "$base" -maxdepth 3 -mindepth 1 -type d 2>/dev/null)
    return 1
}

SDK="$(find_dir "$W2A" platform-tools || find_dir "$W2A" platforms || true)"
NDK="$(find_dir "$W2A" toolchains/llvm/prebuilt || find_dir "$W2A" ndk-build || true)"
JDK="$(find_dir "$W2A" bin/javac || find_dir "$W2A" bin/java || true)"

# NDK внутри SDK/ndk/<ver>
if [ -z "$NDK" ] && [ -n "$SDK" ] && [ -d "$SDK/ndk" ]; then
    NDK="$(ls -1d "$SDK"/ndk/*/ 2>/dev/null | tail -1 | sed 's:/*$::')"
fi

{
    echo '#!/usr/bin/env bash'
    echo '# Generated by scripts/setup_w2a.sh'
    echo 'export W2A_HOME="'"$W2A"'"'
    echo 'export TMPDIR="${TMPDIR:-$HOME/tmp}"'
    echo 'mkdir -p "$TMPDIR"'
    [ -n "$SDK" ] && {
        echo "export ANDROID_HOME=\"$SDK\""
        echo "export ANDROID_SDK_ROOT=\"$SDK\""
        echo 'export PATH="$ANDROID_HOME/platform-tools:$ANDROID_HOME/cmdline-tools/latest/bin:$PATH"'
    }
    [ -n "$NDK" ] && {
        echo "export ANDROID_NDK_HOME=\"$NDK\""
        echo "export NDK=\"$NDK\""
        echo "export ANDROID_NDK_ROOT=\"$NDK\""
    }
    [ -n "$JDK" ] && {
        echo "export JAVA_HOME=\"$JDK\""
        echo 'export PATH="$JAVA_HOME/bin:$PATH"'
    }
    echo
    echo 'echo "env: SDK=$ANDROID_HOME NDK=$ANDROID_NDK_HOME JDK=$JAVA_HOME TMPDIR=$TMPDIR"'
} > scripts/env.sh
chmod 755 scripts/env.sh

if [ -n "$SDK" ]; then
    {
        echo "sdk.dir=$SDK"
        [ -n "$NDK" ] && echo "ndk.dir=$NDK"
    } > android/local.properties
    echo "wrote android/local.properties"
fi

echo "wrote scripts/env.sh"
bash scripts/env.sh
